#!/usr/bin/env node
/**
 * =============================================================================
 * CineBook / Cinemanik 2026 - Automated Supabase Setup & Provisioning Script
 * =============================================================================
 * Automatically sets up Supabase project when provided with a Personal Access Token:
 * 1. Fetches API Keys (anon key, service_role key) via Supabase Management API
 * 2. Injects variables into web/.env.local and .env
 * 3. Deploys full database schema (tables, RLS, functions, triggers, seed data)
 * 4. Ensures storage bucket exists for film posters
 *
 * Usage:
 *   node scripts/setup-supabase.mjs --token <sbp_access_token> --project <project_id_or_url>
 * Or with environment variables:
 *   SUPABASE_ACCESS_TOKEN=sbp_... SUPABASE_PROJECT_ID=... node scripts/setup-supabase.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const webDir = path.resolve(rootDir, 'web');

// Parse CLI args
const args = process.argv.slice(2);
let token = process.env.SUPABASE_ACCESS_TOKEN || '';
let projectRef = process.env.SUPABASE_PROJECT_ID || process.env.NEXT_PUBLIC_SUPABASE_URL || '';

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--token' && args[i + 1]) {
    token = args[i + 1].trim();
    i++;
  } else if ((args[i] === '--project' || args[i] === '--ref') && args[i + 1]) {
    projectRef = args[i + 1].trim();
    i++;
  }
}

// Clean up projectRef if URL was passed
if (projectRef.includes('.supabase.co')) {
  const match = projectRef.match(/https?:\/\/([^.]+)\.supabase\.co/);
  if (match) {
    projectRef = match[1];
  }
}
projectRef = projectRef.replace(/^https?:\/\//, '').replace(/\/.*$/, '').trim();

console.log('\n======================================================');
console.log('🎬 CINEMANIK 2026 - AUTOMATED SUPABASE PROVISIONING');
console.log('======================================================\n');

if (!token) {
  console.error('❌ Error: Supabase Access Token wajib diberikan!');
  console.error('Cara penggunaan:');
  console.error('  node scripts/setup-supabase.mjs --token <sbp_token> --project <project_id>\n');
  console.error('Tips: Buat token di https://supabase.com/dashboard/account/tokens\n');
  process.exit(1);
}

if (!projectRef) {
  console.error('❌ Error: Project Reference ID wajib diberikan!');
  console.error('Contoh: jylapjrkedpbrtobvkvb atau https://jylapjrkedpbrtobvkvb.supabase.co\n');
  process.exit(1);
}

async function runSetup() {
  console.log(`📡 Menghubungkan ke Supabase Management API untuk project: ${projectRef}...`);

  // 1. Fetch API Keys
  let anonKey = '';
  let serviceRoleKey = '';

  try {
    const keysRes = await fetch(`https://api.supabase.com/v1/projects/${projectRef}/api-keys`, {
      method: 'GET',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
    });

    if (!keysRes.ok) {
      const errText = await keysRes.text();
      throw new Error(`Gagal mengambil API keys (${keysRes.status}): ${errText}`);
    }

    const keys = await keysRes.json();
    const anonObj = keys.find((k) => k.name === 'anon' || k.tags === 'anon');
    const serviceObj = keys.find((k) => k.name === 'service_role' || k.tags === 'service_role');

    anonKey = anonObj ? anonObj.api_key : '';
    serviceRoleKey = serviceObj ? serviceObj.api_key : '';

    if (!anonKey) {
      throw new Error('Anon key tidak ditemukan di response Supabase API');
    }

    console.log('✅ API Keys berhasil didapatkan!');
    console.log(`   - Anon Key: ${anonKey.substring(0, 16)}...`);
    if (serviceRoleKey) {
      console.log(`   - Service Role Key: ${serviceRoleKey.substring(0, 16)}...`);
    }
  } catch (err) {
    console.error('❌ Terjadi kesalahan saat mengambil API keys:', err.message);
    process.exit(1);
  }

  // 2. Update .env.local in web/ and root .env
  const supabaseUrl = `https://${projectRef}.supabase.co`;
  const cronSecret = 'cinemanik_cron_' + Math.random().toString(36).substring(2, 15);

  const envContent = `# Cinemanik SMAN 1 Kendal - Supabase Environment Variables
# Auto-generated by scripts/setup-supabase.mjs on ${new Date().toISOString()}

NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey || ''}
CRON_SECRET=${cronSecret}
NEXT_PUBLIC_APP_URL=http://localhost:3000

# Opsional: Layanan email pengiriman tiket (Resend)
RESEND_API_KEY=
SENDER_EMAIL=Cinemanik OSIS <no-reply@sman1kendal.sch.id>
`;

  try {
    fs.writeFileSync(path.join(webDir, '.env.local'), envContent, 'utf-8');
    fs.writeFileSync(path.join(rootDir, '.env'), envContent, 'utf-8');
    console.log('✅ File .env.local dan .env berhasil diperbarui dengan kredensial baru!');
  } catch (err) {
    console.warn('⚠️ Gagal menulis file env:', err.message);
  }

  // 3. Read and Deploy Schema SQL
  const schemaPath = path.join(rootDir, 'supabase', 'schema_full_production.sql');
  if (!fs.existsSync(schemaPath)) {
    console.error(`❌ File skema tidak ditemukan di ${schemaPath}`);
    process.exit(1);
  }

  console.log(`📖 Membaca skema database dari supabase/schema_full_production.sql...`);
  const sqlQuery = fs.readFileSync(schemaPath, 'utf-8');

  console.log(`🚀 Menjalankan migrasi database di Supabase Project (${projectRef})...`);

  try {
    const queryRes = await fetch(`https://api.supabase.com/v1/projects/${projectRef}/database/query`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ query: sqlQuery }),
    });

    if (!queryRes.ok) {
      const errText = await queryRes.text();
      console.warn(`⚠️ Catatan eksekusi migrasi (${queryRes.status}): ${errText}`);
      console.log('ℹ️ Jika beberapa objek sudah ada sebelumnya, query tetap berhasil sebagian.');
    } else {
      console.log('✅ Skema database, fungsi RPC, RLS policies, dan demo seed berhasil diterapkan!');
    }
  } catch (err) {
    console.error('❌ Gagal menjalankan query database:', err.message);
  }

  console.log('\n======================================================');
  console.log('🎉 SETUP SUPABASE SELESAI!');
  console.log('======================================================');
  console.log(`Project URL : ${supabaseUrl}`);
  console.log(`Environment : web/.env.local (terisi otomatis)`);
  console.log(`Siap deploy ke Vercel!`);
  console.log('======================================================\n');
}

runSetup().catch((err) => {
  console.error('Fatal setup error:', err);
  process.exit(1);
});
